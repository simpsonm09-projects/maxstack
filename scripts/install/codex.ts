/** Reads a SKILL.md frontmatter the way the generator does: the block between the first two --- lines, one key per line. */
export function readSkillFields(path: string, label: string): Map<string, string> {
  const text = readFileSync(path, 'utf8');
  const lines = text.replace(/^\uFEFF/, '').split(/\r?\n/);
  const end = lines.indexOf('---', 1);
  if (lines.length === 0 || !ordinalEqual(lines[0], '---') || end < 1) {
    throw new Error(`${label} needs a --- frontmatter block.`);
  }
  const fields = new Map<string, string>();
  for (let index = 1; index < end; index++) {
    const match = /^([A-Za-z][\w-]*):\s*(.*)$/.exec(lines[index] as string);
    if (!match) continue;
    let value = (match[2] as string).trim();
    const quoted = /^(["'])(.*)\1$/.exec(value);
    if (quoted) value = quoted[2] as string;
    fields.set(match[1] as string, value);
  }
  return fields;
}

/** Every entry of a skill folder, with links listed and never followed. A link anywhere in the skill is refused. */
export function assertSkillFolder(folder: string, label: string, runtime = 'codex'): void {
  if (testReparsePoint(folder)) {
    throw new Error(
      `${label} is a symbolic link or junction, so ${runtime} cannot take it. Replace it with a folder.`,
    );
  }
  for (const entry of getTreeEntries(folder, 'owned')) {
    if (entry.link !== null) {
      throw new Error(
        `${label} holds a symbolic link or junction at ${entry.relative}, which a skill may not hold.`,
      );
    }
  }
}

/** The frontmatter a skill must carry. A model key is refused, since maxstack sets no model. */
export function assertSkillFields(path: string, name: string, label: string): void {
  const fields = readSkillFields(path, label);
  if (fields.has('model')) throw new Error(`${label}: frontmatter model is not allowed; maxstack sets no model.`);
  if (!testNonEmptyString(fields.get('name'))) throw new Error(`${label}: frontmatter name is missing or empty.`);
  if (!ordinalEqual(fields.get('name'), name)) {
    throw new Error(
      `${label}: frontmatter name '${safeName(fields.get('name'))}' must equal the folder name '${safeName(name)}'.`,
    );
  }
  if (!testNonEmptyString(fields.get('description'))) {
    throw new Error(`${label}: frontmatter description is missing or empty.`);
  }
}

function testNonEmptyString(value: unknown): boolean {
  return typeof value === 'string' && value.trim().length > 0;
}

/** Copies a skill folder, leaving out node_modules at any depth, as the generator does. */
export function copySkillTree(source: string, destination: string): void {
  mkdirSync(destination, { recursive: true });
  for (const child of readdirSync(source, { withFileTypes: true })) {
    if (ordinalEqual(child.name, 'node_modules')) continue;
    const from = join(source, child.name);
    const target = join(destination, child.name);
    if (child.isDirectory()) copySkillTree(from, target);
    else copyFileSync(from, target);
  }
}

/** The skills the selected runtime's layers contribute, in layer order. */
export function getLayerSkills(layers: readonly LayerModel[], runtime = 'codex'): SkillEntry[] {
  const skills: SkillEntry[] = [];
  const claimed = new Map<string, string>();
  const selected = layers.filter((layer) => Object.hasOwn(layer.runtimes, runtime));
  for (const layer of selected) {
    if (layer.root === null) continue;
    const skillsRoot = joinMaxstackPath(layer.root, 'skills');
    if (!isDirectory(skillsRoot)) continue;
    if (testReparsePoint(skillsRoot)) {
      throw new Error(
        `Layer '${safeName(layer.name)}' has a symbolic link or junction at skills, which ${runtime} cannot read.`,
      );
    }
    const names: string[] = [];
    for (const child of readdirSync(skillsRoot, { withFileTypes: true })) {
      if (child.name.startsWith('.')) continue;
      if (!child.isDirectory()) {
        writeWarning(`ignored skills/${child.name} in layer '${layer.name}': not a skill folder`);
        continue;
      }
      names.push(child.name);
    }
    const seen = new Map<string, string>();
    for (const name of names) {
      const folded = name.toLowerCase();
      if (seen.has(folded)) {
        throw new Error(
          `Layer '${safeName(layer.name)}' has skill folders whose names differ only by case, which ${runtime} cannot tell apart: ${safeName(seen.get(folded))} and ${safeName(name)}.`,
        );
      }
      seen.set(folded, name);
    }
    for (const name of sortUtf8(names)) {
      const label = `Layer '${safeName(layer.name)}' skill '${safeName(name)}'`;
      if (!/^[A-Za-z0-9][A-Za-z0-9-]*$/.test(name)) {
        throw new Error(`${label}: skill folder names must be letters, digits, and hyphens.`);
      }
      const folder = joinMaxstackPath(skillsRoot, name);
      assertSkillFolder(folder, label, runtime);
      const skillFile = readdirSync(folder, { withFileTypes: true }).find(
        (entry) => entry.isFile() && ordinalEqual(entry.name, 'SKILL.md'),
      );
      if (!skillFile) throw new Error(`${label}: a file named exactly SKILL.md is required.`);
      assertSkillFields(join(folder, skillFile.name), name, label);
      const folded = name.toLowerCase();
      if (claimed.has(folded)) {
        throw new Error(
          `duplicate skill ${safeName(name)} across layers: ${safeName(claimed.get(folded))} and ${safeName(layer.name)} both name it, and ${runtime} finds a skill by its folder name. Rename one of them.`,
        );
      }
      claimed.set(folded, layer.name);
      skills.push({ name, layer: layer.name, source: folder, sha256: getTreeSha256(folder) });
    }
  }
  return skills;
}

/** Whether a path under .agents/skills is one the lock records as codex's own folder, with the record. */
export function getCodexRecord(owned: readonly (OwnedRecord | null)[], relative: string): OwnedRecord | null {
  return (
    owned.find(
      (record) =>
        record !== null &&
        ordinalEqual(record.path, relative) &&
        ordinalEqual(record.kind, 'dir') &&
        getOwnedRuntimeClaims(record).some((claim) => ordinalIn(claim, ['codex', 'antigravity'])),
    ) ?? null
  );
}

export function assertCodexSkillsPath(): void {
  // Folders above the workspace are the user's choice and may be system links, so only the folders below it are checked.
  const workspace = resolve(S.workspace);
  let current = workspace;
  for (const segment of ['.agents', 'skills']) {
    current = join(current, segment);
    if (!pathExists(current)) continue;
    if (testReparsePoint(current)) {
      throw new Error(`Codex and Antigravity target '${current}' is a link or reparse point, so nothing was written.`);
    }
    if (!isDirectory(current)) {
      throw new Error(`Codex and Antigravity target '${current}' exists and is not a directory, so nothing was written.`);
    }
  }
}

export function assertCodexDestinationWithinWorkspace(path: string): void {
  const workspace = resolve(S.workspace).replace(/[\\/]+$/, '');
  const target = resolve(path);
  const prefix = `${workspace}/`;
  const targetText = target.replaceAll('\\', '/');
  if (!targetText.startsWith(prefix)) {
    throw new Error(`Agent skill target '${target}' resolves outside the workspace, so nothing was written.`);
  }
  const rel = relative(workspace, target);
  let current = workspace;
  for (const segment of rel.split(/[\\/]+/).filter(Boolean)) {
    current = join(current, segment);
    if (pathExists(current) && testReparsePoint(current)) {
      throw new Error(`Agent skill target '${current}' is a link or reparse point, so nothing was written.`);
    }
  }
}

export function assertCodexSkillName(name: string): void {
  if (/^(?:con|prn|aux|nul|com[1-9¹²³]|lpt[1-9¹²³])(?:\..*)?$/i.test(name)) {
    throw new Error(`Agent skill folder '${safeName(name)}' is a reserved Windows device name.`);
  }
}

/** Before any write: a skill folder that exists must be one the lock records as codex's and still holds the recorded tree. */
export function assertCodexSkillTargets(
  skills: SkillEntry[],
  owned: readonly (OwnedRecord | null)[] | null,
  preserveModified = false,
): void {
  assertCodexSkillsPath();
  for (const skill of skills) {
    assertCodexSkillName(skill.name);
    const rel = `${CODEX_SKILL_FOLDER}/${skill.name}`;
    const full = joinMaxstackPath(S.workspace, convertToMaxstackPath(rel));
    assertCodexDestinationWithinWorkspace(full);
    const parent = dirname(full);
    let same: string[] = [];
    if (isDirectory(parent)) {
      same = readdirSync(parent).filter((name) => ordinalEqualIgnoreCase(name, skill.name));
    }
    if (same.length > 1) {
      throw new Error(`${rel} collides with multiple skill folders by case, so nothing was written.`);
    }
    if (same.length === 1 && !ordinalEqual(same[0], skill.name)) {
      throw new Error(`${rel} collides with skill folder '${safeName(same[0])}' by case, so nothing was written.`);
    }
    if (!pathExists(full)) continue;
    const record = getCodexRecord(owned ?? [], rel);
    if (record === null) {
      throw new Error(
        `${rel} already exists and maxstack did not write it, so nothing was written. Move it aside, then rerun -Apply.`,
      );
    }
    if (testReparsePoint(full)) throw new Error(`${rel} is a link or reparse point, so nothing was written.`);
    if (!ordinalEqual(getTreeSha256(full), record.sha256)) {
      if (!preserveModified && record.runtimes === undefined) {
        throw new Error(
          `${rel} changed since the last apply, so nothing was written. Move its changes aside, or delete it, then rerun -Apply.`,
        );
      }
      writeHost(`Kept ${rel}: it changed since the last apply.`);
      skill.preserve = true;
      skill.prior = record;
    }
  }
}

/** Writes the codex skills, after the checks above. With removeStale, a recorded skill that no layer ships now is removed. */
export function writeCodexSkills(
  skills: readonly SkillEntry[],
  owned: readonly (OwnedRecord | null)[] | null,
  removeStale = true,
): void {
  const wanted = skills.map((skill) => `${CODEX_SKILL_FOLDER}/${skill.name}`);
  if (removeStale) {
    for (const record of owned ?? []) {
      if (record === null) continue;
      if (!getOwnedRuntimeClaims(record).some((claim) => ordinalIn(claim, ['codex', 'antigravity']))) continue;
      if (!ordinalEqual(record.kind, 'dir') || ordinalIn(record.path, wanted)) continue;
      const full = joinMaxstackPath(S.workspace, convertToMaxstackPath(record.path));
      if (!isDirectory(full)) continue;
      if (testReparsePoint(full) || !ordinalEqual(getTreeSha256(full), record.sha256)) {
        writeHost(`Kept ${record.path}: it changed since the last apply, and no layer ships it now`);
        continue;
      }
      removeOwnedTree(full);
      writeHost(`Removed the codex skill ${record.path}: no layer ships it now`);
    }
  }
  const root = joinMaxstackPath(S.workspace, convertToMaxstackPath(CODEX_SKILL_FOLDER));
  for (const skill of skills) {
    const full = joinMaxstackPath(root, skill.name);
    if (isTrue(skill.preserve)) continue;
    assertCodexDestinationWithinWorkspace(full);
    removeOwnedTree(full);
    copySkillTree(skill.source, full);
    writeHost(`Copied codex skill '${skill.name}' from layer '${skill.layer}' into ${full}`);
  }
}

/** The installed copy of a selected layer. */
